"""Build planted.py and answer_key.json from reference.py + defects.py.

Deterministic: rerunning produces byte-identical outputs, and the test suite
checks the committed files are current.

    python -m experiments.verifier_recall.build_fixture
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List, Tuple

from experiments.verifier_recall.defects import DEFECTS

HERE = Path(__file__).resolve().parent
REFERENCE = HERE / "reference.py"
PLANTED = HERE / "planted.py"
ANSWER_KEY = HERE / "answer_key.json"

PLANTED_HEADER = (
    '"""Escrow ledger under review (verifier-recall fixture, planted side).\n\n'
    "GENERATED by build_fixture.py from reference.py. Contains deliberate\n"
    "defects; do not import or fix. See answer_key.json.\n"
    '"""\n'
)


def build() -> Tuple[str, List[Dict[str, object]]]:
    """Apply every defect and return (planted source, answer key rows)."""
    text = REFERENCE.read_text()
    # Swap the reference docstring for the planted header so line numbers
    # below are computed against the file reviewers actually see.
    body = text[text.index('"""', 3) + 3:].lstrip("\n")
    text = PLANTED_HEADER + "\n" + body
    for d in DEFECTS:
        if text.count(d.old) != 1:
            raise ValueError(f"{d.id}: anchor text must occur exactly once")
        marker = f"# @@{d.id}@@\n"
        # Put the marker on its own line where the defect lands, then strip it
        # after all substitutions to learn the defect's final line number.
        start = text.index(d.old)
        line_start = text.rfind("\n", 0, start) + 1
        replaced = d.new if d.new else ""
        text = text[:line_start] + marker + text[line_start:start] + replaced + text[start + len(d.old):]
    key = []
    lines = text.split("\n")
    out: List[str] = []
    for line in lines:
        tag = line.strip()
        if tag.startswith("# @@") and tag.endswith("@@"):
            defect_id = tag[4:-2]
            key.append((defect_id, len(out) + 1))
            continue
        out.append(line)
    planted = "\n".join(out)
    by_id = {d.id: d for d in DEFECTS}
    rows = [
        {
            "id": defect_id,
            "file": "planted.py",
            "line": line_no,
            "function": by_id[defect_id].function,
            "category": by_id[defect_id].category,
            "description": by_id[defect_id].description,
        }
        for defect_id, line_no in sorted(key, key=lambda t: t[0])
    ]
    return planted, rows


def main() -> None:
    planted, rows = build()
    PLANTED.write_text(planted)
    ANSWER_KEY.write_text(json.dumps(rows, indent=2) + "\n")
    print(f"wrote {PLANTED.name} and {ANSWER_KEY.name}: {len(rows)} defects")


if __name__ == "__main__":
    main()
